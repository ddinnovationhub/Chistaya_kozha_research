def main():
    done = set()
    if os.path.exists(OUT):
        for line in open(OUT, encoding="utf-8"):
            try:
                done.add(json.loads(line)["inn"])
            except Exception:
                pass
        print("Продолжаю: уже собрано", len(done))
    todo = [i for i in INNS if i not in done]
    if not todo:
        print("Всё уже собрано. Отправьте файл rzn_dump.jsonl агенту:", OUT)
        return
    # ПОРЦИЯ ЗА ЗАХОД (заказчик, 2026-08-29: «забирать по 200 штук для
    # конвейерности»). Enter = 200; число = столько; «все» = весь остаток.
    limit = 200
    if len(sys.argv) > 1:
        arg = sys.argv[1].strip().lower()
        limit = len(todo) if arg in ("все", "all", "0") else int(arg)
    else:
        try:
            ans = input("Сколько ИНН собрать в этом заходе? "
                        "[Enter = 200, число, или «все»]: ").strip().lower()
            if ans in ("все", "all", "0"):
                limit = len(todo)
            elif ans:
                limit = int(ans)
        except Exception:
            pass
    todo = todo[:limit]
    print("В этом заходе:", len(todo), "ИНН (~%d мин)" % (len(todo) * 4.5 // 60))
    # Подбор режима подключения (2026-08-29, URLError у заказчика):
    # A) как настроена система (прокси/VPN из Windows) с проверкой TLS;
    # B) напрямую, мимо системного прокси; C/D) то же с отключённой
    # проверкой TLS (только чтение публичного реестра; каждая строка
    # ответа потом сверяется по ИНН на стороне агента).
    import ssl
    modes = []
    for proxy in (None, {}):
        for verify in (True, False):
            handlers = [urllib.request.HTTPCookieProcessor(CookieJar())]
            if proxy == {}:
                handlers.append(urllib.request.ProxyHandler({}))
            if not verify:
                ctx = ssl.create_default_context()
                ctx.check_hostname = False
                ctx.verify_mode = ssl.CERT_NONE
                handlers.append(urllib.request.HTTPSHandler(context=ctx))
            modes.append((("системный прокси" if proxy is None else "напрямую")
                          + (", TLS проверяется" if verify else ", БЕЗ проверки TLS"),
                          urllib.request.build_opener(*handlers)))
    opener = None
    print("Открываю сессию реестра (подбираю режим подключения)...")
    for name, op in modes:
        try:
            req = urllib.request.Request(RZN_URL, headers={
                "User-Agent": HEADERS["User-Agent"], "Accept": "text/html"})
            op.open(req, timeout=25).read()
            opener = op
            print("  режим:", name, "- РАБОТАЕТ")
            break
        except Exception as e:
            print("  режим:", name, "-", type(e).__name__,
                  str(getattr(e, "reason", e))[:90])
    if opener is None:
        print()
        print("Ни один режим не подключился. Пришлите агенту текст выше -")
        print("особенно то, что написано после URLError.")
        return
    ok = fail = 0
    out = open(OUT, "a", encoding="utf-8")
    for n, inn in enumerate(todo, 1):
        body = urllib.parse.urlencode({"draw": "1", "start": "0",
                                       "length": "100", "q_no": inn}).encode()
        data = None
        for att in range(3):
            try:
                r = opener.open(urllib.request.Request(
                    RZN_AJAX, data=body, headers=HEADERS), timeout=40)
                data = json.loads(r.read().decode("utf-8"))
                break
            except Exception as e:
                print("  повтор (%s/3) %s: %s" % (att + 1, inn, type(e).__name__))
                time.sleep(10)
        if data is None:
            fail += 1
        else:
            ok += 1
            out.write(json.dumps({"inn": inn, "data": data},
                                 ensure_ascii=False) + "\n")
            out.flush()
        if n % 10 == 0 or n == len(todo):
            print("%d/%d готово (ок %d, сбоев %d)" % (n, len(todo), ok, fail))
        time.sleep(3)
    out.close()
    print()
    print("ГОТОВО. Отправьте агенту файл:", OUT)
    if fail:
        print("Сбоев:", fail, "- запустите скрипт ещё раз, он доберёт их.")


