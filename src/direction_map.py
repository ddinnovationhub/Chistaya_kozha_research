def load_gold() -> dict:
    """name_norm → (вердикт, альтернатива, спорная?)."""
    import openpyxl
    import yaml
    disputed = {norm(r["name"]) for r in yaml.safe_load(
        open(DIRECTIONS_YAML, encoding="utf-8"))["disputed_gold_rows"]}
    wb = openpyxl.load_workbook(GOLD_XLSX, read_only=True, data_only=True)
    gold = {}
    for r in wb["Маппинг_1000"].iter_rows(min_row=2, values_only=True):
        name, verdict = str(r[2] or ""), str(r[4] or "").strip()
        alt = str(r[5] or "").strip() or None
        if not verdict:
            continue
        k = norm(name)
        gold[k] = (verdict, alt, k in disputed)
    wb.close()
    return gold


def cmd_eval():
    gold = load_gold()
    ok = miss = 0; nocov = 0
    conf = Counter(); errs = []
    strict_ok = 0
    for k, (verdict, alt, disputed) in gold.items():
        if disputed:
            continue
        d, method, c, ev = classify(k)
        if d is None:
            nocov += 1
            continue
        if d == verdict:
            strict_ok += 1
        if d == verdict or (alt and d == alt):
            ok += 1
        else:
            miss += 1
            conf[(d, verdict)] += 1
            errs.append((k[:60], d, verdict, method, ev))
    total = ok + miss
    print(f"голд (без 9 спорных): {ok+miss+nocov}")
    print(f"покрыто ступенью 1: {total} ({total/(total+nocov):.0%}) · "
          f"точность (вердикт|альтернатива): {ok}/{total} = "
          f"{ok/max(total,1):.1%} · строго по вердикту: "
          f"{strict_ok/max(total,1):.1%} · остаток агенту: {nocov}")
    print("\nтоп-ошибки (наше → голд):")
    for (a, b), v in conf.most_common(15):
        print(f"  {v:3d}  {a[:38]:38s} → {b[:38]}")
    for e in errs[:25]:
        print("   ·", e[0], "|", e[1], "→", e[2], "|", e[4][:50])
    return errs


