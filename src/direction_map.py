def cmd_run():
    gold = load_gold()
    db = open_db()
    # кодовые строки пересобираются с нуля (идемпотентность);
    # суждения агента — несгораемы
    db.execute("DELETE FROM name_directions WHERE method NOT LIKE 'агент%'")
    db.commit()
    p = sqlite3.connect(f"file:{PRICES_DB}?mode=ro", uri=True)
    # уникальные названия + частота + типичный раздел/код
    agg = {}
    for name, sec, code in p.execute(
            "select name_raw, section, code from price_items"):
        k = norm(strip_ui(name or ""))
        if k not in agg:
            agg[k] = [0, Counter(), Counter(), name]
        a = agg[k]; a[0] += 1
        if sec: a[1][sec] += 1
        if code: a[2][code] += 1
    print("уникальных названий:", len(agg))
    now = datetime.datetime.now().isoformat(timespec="seconds")
    stats = Counter(); rows = []; echo_log = []
    for k, (n, secs, codes, raw) in agg.items():
        sec = secs.most_common(1)[0][0] if secs else ""
        code = codes.most_common(1)[0][0] if codes else ""
        if k in gold and not gold[k][2]:
            verdict, alt = gold[k][0], gold[k][1]
            d, m, c, ev = verdict, "голд: проверка заказчика", "выс", \
                "Маппинг_1000 v4"
            if alt and alt != verdict:
                dc = classify(raw, sec, code)[0]
                if dc == alt:
                    d, m, ev = alt, "голд: альтернатива заказчика", \
                        f"эхо-дефект: вердикт «{verdict}», альт+код: «{alt}»"
                    echo_log.append((raw[:120], verdict, alt))
        elif k in gold:
            d, m, c, ev = None, "", "", ""   # спорная — агенту
        else:
            d, m, c, ev = classify(raw, sec, code)
        if d:
            rows.append((k, d, m, c, ev, n, now))
            stats[m.split(":")[0] + ": " + d] += n
        else:
            stats["ОСТАТОК"] += n
    db.executemany("INSERT OR REPLACE INTO name_directions VALUES (?,?,?,?,?,?,?)",
                   rows)
    db.commit()
    covered = sum(v for k, v in stats.items() if k != "ОСТАТОК")
    total = covered + stats["ОСТАТОК"]
    print(f"классифицировано кодом: {len(rows)} названий, "
          f"{covered} позиций из {total} ({covered/total:.0%})")
    print(f"остаток на суждение агента: {stats['ОСТАТОК']} позиций")
    if echo_log:
        print(f"голд-строк переведено на альтернативу заказчика "
              f"(эхо-дефект): {len(echo_log)}")
    return db


