def is_ui_garbage(stripped: str) -> bool:
    t = norm(stripped)
    if len(t) < 3:
        return True
    if _NAMES_ROW.search(t):
        return True
    return any(p.match(t) for p in _PURE_UI_RE)


def is_fragment(stripped: str) -> bool:
    """«Обрывок»: кусок названия без опознаваемой услуги."""
    t = norm(stripped)
    words = t.split()
    if not words:
        return True
    # одно короткое слово-предлог/союз/обрывок
    if len(words) <= 2 and all(len(w) <= 3 for w in words):
        return True
    return False


