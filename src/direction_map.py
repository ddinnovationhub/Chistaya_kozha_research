def cmd_batches(size=400):
    """Остаток на суждение агента: батчи по убыванию частоты."""
    gold = load_gold()
    db = open_db()
    done = {r[0] for r in db.execute("select name_norm from name_directions")}
    p = sqlite3.connect(f"file:{PRICES_DB}?mode=ro", uri=True)
    agg = {}
    for name, sec, dom in p.execute(
            "select name_raw, section, domain from price_items"):
        k = norm(strip_ui(name or ""))
        if k in done:
            continue
        if k not in agg:
            agg[k] = [0, Counter(), Counter(), name]
        a = agg[k]; a[0] += 1; a[1][sec or ""] += 1; a[2][dom] += 1
    items = sorted(agg.items(), key=lambda kv: -kv[1][0])
    day = datetime.date.today().isoformat()
    out = []
    for i in range(0, len(items), size):
        batch = [{"name_norm": k, "name_raw": v[3][:200], "positions": v[0],
                  "section": v[1].most_common(1)[0][0][:100],
                  "domains": [d for d, _ in v[2].most_common(3)]}
                 for k, v in items[i:i + size]]
        fn = f"output/направления_на_суждение_{day}_батч{i//size:03d}.json"
        json.dump({"инструкция": "направление СТРОГО из dictionaries/"
                   "directions.yaml categories; правила R1-R9 обязательны",
                   "строки": batch},
                  open(fn, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        out.append(fn)
    print(f"остаток: {len(items)} названий → {len(out)} батчей по {size}")
    return out


def cmd_merge(path):
    import yaml
    cats = set(yaml.safe_load(open(DIRECTIONS_YAML, encoding="utf-8"))
               ["categories"])
    data = json.load(open(path, encoding="utf-8"))
    db = open_db()
    now = datetime.datetime.now().isoformat(timespec="seconds")
    # полный список реальных ключей: обрезанный ключ суждения
    # разворачивается по префиксу, сироты не создаются
    p2 = sqlite3.connect(f"file:{PRICES_DB}?mode=ro", uri=True)
    cnt = {}
    for (nm,) in p2.execute("select name_raw from price_items"):
        kk = norm(strip_ui(nm or ""))
        cnt[kk] = cnt.get(kk, 0) + 1
    classified = {r[0] for r in db.execute(
        "select name_norm from name_directions")}
    ok = bad = 0
    for row in data["строки"] if "строки" in data else data:
        d = row.get("direction") or row.get("направление")
        k = row.get("name_norm")
        if not k or d not in cats:
            bad += 1
            continue
        keys = [k] if k in cnt else             [kk for kk in cnt if kk.startswith(k) and kk not in classified]
        if not keys:
            bad += 1
            continue
        for kk in keys:
            db.execute(
                "INSERT OR REPLACE INTO name_directions VALUES (?,?,?,?,?,?,?)",
                (kk, d, "агент: суждение", row.get("уверенность", "сред"),
                 row.get("улика", "")[:200], cnt[kk], now))
            classified.add(kk)
        ok += 1
    db.commit()
    print(f"влито {ok}, отклонено {bad} (нет в каноне/нет ключа/нет пары)")


