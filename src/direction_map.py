_compiled = None


def _rules():
    global _compiled
    if _compiled is None:
        _compiled = []
        for d, conf, inc, exc in RULES:
            _compiled.append((d, conf,
                              [re.compile(p) for p in inc],
                              [re.compile(p) for p in exc]))
    return _compiled


def classify(name_raw: str, section: str = "", code: str = "") -> tuple:
    """→ (направление|None, метод, уверенность, улика)."""
    stripped = strip_ui(name_raw)
    if is_ui_garbage(stripped):
        return ("Брак разметки (UI-текст)", "код: UI-мусор", "выс",
                f"после отрезки UI: «{norm(stripped)[:40]}»")
    t = norm(stripped)
    # приёмы по специальности — раньше правил (иначе «прием хирурга» уйдёт
    # в общее правило «хирург», что совпадает, но улика точнее)
    if _RECEPTION.search(t):
        for pat, d in SPECIALTY_MAP:
            m = re.search(pat, t)
            if m:
                return (d, "код: приём по специальности", "выс",
                        f"специальность «{m.group(0)}»")
    for d, conf, inc, exc in _rules():
        for p in inc:
            m = p.search(t)
            if m:
                if any(x.search(t) for x in exc):
                    break  # заблокировано гардом — к следующему правилу
                return (d, "код: правило", conf, f"ключ «{m.group(0)[:40]}»")
    # код 804н
    c = norm(code or "").replace(" ", "")
    if c:
        for pref, d in CODE_PREFIX:
            if c.startswith(pref.replace(".", "")) or c.startswith(pref):
                return (d, "код: 804н-префикс", "сред", f"код {code[:20]}")
    # раздел прайса тем же движком (слабее)
    if section:
        ts = norm(strip_ui(section))
        if ts and not is_ui_garbage(section):
            for d, conf, inc, exc in _rules():
                for p in inc:
                    m = p.search(ts)
                    if m and not any(x.search(ts) for x in exc):
                        return (d, "код: раздел прайса", "сред",
                                f"раздел «{ts[:40]}», ключ «{m.group(0)[:30]}»")
    if is_fragment(stripped):
        return ("Брак разметки (обрывок)", "код: обрывок", "сред",
                f"«{norm(stripped)[:40]}»")
    return (None, "", "", "")


