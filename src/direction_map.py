def norm(s: str) -> str:
    """Нормализация для ключа: нижний регистр, ё→е, только буквы/цифры."""
    s = (s or "").lower().replace("ё", "е")
    s = re.sub(r"_x000d_|\s+", " ", s)
    s = re.sub(r"[^a-zа-я0-9 ]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def strip_ui(s: str) -> str:
    """Отрезка UI-хвостов ДО классификации (правило R5)."""
    s = _FIO.sub(" ", s or "")
    s = re.sub(r"_x000D_|\s+", " ", s)
    prev = None
    while prev != s:
        prev = s
        s = _UI_TAIL.sub("", s)
        s = _UI_HEAD.sub("", s)
    return s.strip(" ,;·-–—")


