"""Обезличивание ФИО (152-ФЗ, принцип минимизации).

ПОЧЕМУ ЭТОТ МОДУЛЬ ПОЯВИЛСЯ ТОЛЬКО 2026-09-04. Правило «персональные данные
врачей не собираются, ФИО в таблице нет» записано в CLAUDE.md и
config/sources.yaml с самого начала, а реализация значилась в бэклоге
Юриста OSINT с 2026-08-27 («проверить, что в паспорт не попадают ФИО врачей
перед отправкой во внешние сервисы») и сделана не была. Паспорт сайта —
дословный слепок меню, заголовков и контакт-блока, поэтому блок «Наши
врачи» попадал в него целиком: 421 паспорт из 1134 и 267 прайс-позиций
содержали настоящие ФИО. Правило без кода — это не правило.

ЧТО ДЕЛАЕМ. ФИО заменяются меткой «[ФИО]» ДО записи в базу — ни в osint.db,
ни в prices.db, ни в выгрузках, ни в запросах к судьям-нейронкам имён быть
не должно. Смысл для классификации сохраняется: судье важно, что на сайте
есть врачи и какие у них специальности, а не как их зовут.

ЧТО НЕ ТРОГАЕМ. Названия юрлиц («ИП Иванова М.П.») приходят из реестров
ЕГРЮЛ/РЗН и являются сведениями о хозяйствующем субъекте, а не досье на
человека; они живут в отдельных полях (name, licensee) и через этот модуль
не проходят. Название клиники вида «Клиника доктора Петрова» — часть бренда
и остаётся: шаблоны ниже требуют либо отчества, либо инициалов, чего в
брендах обычно нет.
"""

import re

# Отчество — самый надёжный признак ФИО в русском тексте: «Иванов Пётр
# Сергеевич», «ИВАНОВА МАРИЯ ПЕТРОВНА», «Пётр Сергеевич Иванов».
_PATRONYMIC = (r"(?:[А-ЯЁ][а-яё]+(?:ович|евич|ьевич|овна|евна|ьевна"
               r"|ична|инична|ьич|ич|ична))")   # ьич/ич — Ильич, Кузьмич, Лукич
_SURNAME = r"(?:[А-ЯЁ][а-яё]+(?:ов|ев|ёв|ин|ын|ский|цкий|ская|цкая|ова|ева|ёва|ина|ына|ко|ук|юк|ян|швили|дзе|оглы|улы)?)"

_FIO_PATTERNS = [
    # Фамилия Имя Отчество / Имя Отчество Фамилия — в любом порядке
    re.compile(rf"\b{_SURNAME}\s+[А-ЯЁ][а-яё]+\s+{_PATRONYMIC}\b"),
    re.compile(rf"\b[А-ЯЁ][а-яё]+\s+{_PATRONYMIC}\s+{_SURNAME}\b"),
    # ПРОПИСЬЮ: «ШАЙХУТДИНОВА ГУЛЬНАЗ КАМИЛОВНА»
    re.compile(r"\b[А-ЯЁ]{2,}\s+[А-ЯЁ]{2,}\s+[А-ЯЁ]{2,}"
               r"(?:ОВИЧ|ЕВИЧ|ЬЕВИЧ|ОВНА|ЕВНА|ЬЕВНА|ИЧНА|ИНИЧНА)\b"),
    # Фамилия с инициалами: «Иванов П. С.», «Иванов П.С.»
    re.compile(rf"\b{_SURNAME}\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.(?!\w)"),
    # Инициалы перед фамилией: «П. С. Иванов»
    re.compile(rf"\b[А-ЯЁ]\.\s?[А-ЯЁ]\.\s?{_SURNAME}\b"),
    # Имя Отчество без фамилии: «Мария Петровна» (обращение в отзывах)
    re.compile(rf"\b[А-ЯЁ][а-яё]+\s+{_PATRONYMIC}\b"),
]

MASK = "[ФИО]"

# Слова, после которых заглавная пара — не человек, а организация/место.
# Защищает «Городская Клиническая Больница», «Проспект Победы Зеленодольск».
_NOT_A_PERSON = re.compile(
    r"\b(?:ООО|ОАО|ЗАО|ПАО|АО|ИП|АНО|ГБУЗ|ГАУЗ|улица|ул|проспект|пр-кт|"
    r"переулок|шоссе|площадь|город|клиника|центр|больница|поликлиника)\b",
    re.IGNORECASE)


def mask_fio(text: str) -> str:
    """Текст → тот же текст с ФИО, заменёнными на «[ФИО]»."""
    if not text:
        return text
    out = str(text)
    for pat in _FIO_PATTERNS:
        out = pat.sub(lambda m: (m.group(0) if _NOT_A_PERSON.search(m.group(0))
                                 else MASK), out)
    # «[ФИО] | [ФИО] | [ФИО]» — список врачей схлопывается в одну метку:
    # для суждения важен факт «врачи перечислены», а не их число
    out = re.sub(r"(?:\[ФИО\]\s*[|,·—-]?\s*){2,}", MASK + " ", out)
    return out


def has_fio(text: str) -> bool:
    """Есть ли в тексте необезличенное ФИО (для тестов и аудита базы)."""
    if not text:
        return False
    s = str(text)
    return any(m for pat in _FIO_PATTERNS for m in pat.finditer(s)
               if not _NOT_A_PERSON.search(m.group(0)))
