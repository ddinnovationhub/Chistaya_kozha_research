"""Ошибки прогона. Контракт: исчерпание квоты и ошибка авторизации
останавливают прогон с сохранением чекпойнта, а не пропускаются молча."""


class QuotaExhaustedError(RuntimeError):
    """Лимит API исчерпан (коды 402/429). Прогон приостановлен, данные сохранены."""


class AuthError(RuntimeError):
    """Ошибка авторизации API (коды 401/403). Проверить GitHub Secrets."""


class MissingSourceError(RuntimeError):
    """Попытка записи узла/ребра/Claim без source_id — ошибка выполнения, прогон останавливается."""


class BudgetExceededError(RuntimeError):
    """Программный потолок бюджета пробит. Единственная реальная защита от
    перерасхода: Yandex Cloud затраты не ограничивает (решение заказчика 2026-08-24)."""
