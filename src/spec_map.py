# Строки-исключения: правило первого упоминания даёт неверный ответ.
EXCEPTIONS = [
    # вакцинация: приём педиатра/терапевта ради прививки — это вакцинальный контур,
    # но специальность важнее для профиля клиники, поэтому переопределяем только
    # строки, где приём НЕ назван, а названа вакцина.
    (r'^вакцина .*прием (педиатра|врача) и вакцина', 'Вакцинация'),
]

_compiled = [(re.compile(p), d) for p, d in RULES]
_exc = [(re.compile(p), d) for p, d in EXCEPTIONS]


def classify(name_norm: str):
    """Вернуть (направление, позиция_совпадения, фрагмент) или (None, None, None)."""
    for rx, d in _exc:
        if rx.search(name_norm):
            return d, -1, 'исключение'
    best = None
    for rx, d in _compiled:
        m = rx.search(name_norm)
        if m and (best is None or m.start() < best[1]):
            best = (d, m.start(), m.group(0))
    return best if best else (None, None, None)
